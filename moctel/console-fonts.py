#!/usr/bin/env python3
# Generate packages/xo-web/src/common/console-fonts.js: the printable ASCII
# glyphs of common Linux console fonts (console-setup) and of the SeaVGABIOS
# font (text mode before a console font is loaded), all public domain. Used to
# read the VM console text exactly (see console-ocr.js).
#
#   moctel/console-fonts.py > packages/xo-web/src/common/console-fonts.js
#   npx prettier --write packages/xo-web/src/common/console-fonts.js
import gzip
import re
import struct
import urllib.request

FONTS = {
    'VGA': 'Uni2-VGA16',
    'Fixed': 'Uni2-Fixed16',
    'Terminus': 'Uni2-Terminus16',
    'TerminusBold': 'Uni2-TerminusBold16',
    'TerminusBoldVGA': 'Uni2-TerminusBoldVGA16',
}
SEABIOS_FONTS = 'https://raw.githubusercontent.com/coreboot/seabios/28aa46349b97ef0ebf742ae4fb9f9fad03578670/vgasrc/vgafonts.c'
CHARS = [chr(c) for c in range(33, 127)]  # space is an empty cell


def load(name):
    data = gzip.open(f'/usr/share/consolefonts/{name}.psf.gz').read()
    if data[:2] == b'\x36\x04':  # PSF1
        mode, height = data[2], data[3]
        count = 512 if mode & 1 else 256
        width, size, offset = 8, height, 4
        table = data[offset + count * size:] if mode & 2 else b''
        unicode_map = {}
        glyph = 0
        for i in range(0, len(table) - 1, 2):
            code = struct.unpack('<H', table[i:i + 2])[0]
            if code == 0xFFFF:
                glyph += 1
            elif code != 0xFFFE:
                unicode_map.setdefault(chr(code), glyph)
    else:  # PSF2
        _, _, offset, flags, count, size, height, width = struct.unpack('<8I', data[:32])
        table = data[offset + count * size:] if flags & 1 else b''
        unicode_map = {}
        for glyph, entry in enumerate(table.split(b'\xff')[:count]):
            for char in entry.split(b'\xfe')[0].decode('utf-8', 'ignore'):
                unicode_map.setdefault(char, glyph)
    assert width == 8 and height == 16, (name, width, height)
    glyphs = {}
    for char in CHARS:
        start = offset + unicode_map[char] * size
        glyphs[char] = data[start:start + size].hex()
    return glyphs


def load_seabios():
    source = urllib.request.urlopen(SEABIOS_FONTS).read().decode()
    body = re.search(r'vgafont16\[256 \* 16\] VAR16 = \{(.*?)\};', source, re.S).group(1)
    data = bytes(int(byte, 16) for byte in re.findall(r'0x([0-9a-fA-F]{2})', re.sub(r'/\*.*?\*/', '', body, flags=re.S)))
    assert len(data) == 256 * 16
    return {char: data[ord(char) * 16:(ord(char) + 1) * 16].hex() for char in CHARS}


fonts = {}
for label, glyphs in [*((label, load(name)) for label, name in FONTS.items()), ('BIOS', load_seabios())]:
    if glyphs not in fonts.values():
        fonts[label] = glyphs

print('// generated by moctel/console-fonts.py, do not edit')
print('//')
print('// printable ASCII glyphs (8x16, one hex byte per row) of Linux console fonts')
print('// from console-setup and of the SeaVGABIOS font, all public domain')
print()
print(f"export const CHARS = '{''.join(CHARS).replace(chr(92), chr(92) * 2).replace(chr(39), chr(92) + chr(39))}'")
print()
print('export const FONTS = {')
for label, glyphs in fonts.items():
    print(f"  {label}: '{''.join(glyphs[c] for c in CHARS)}',")
print('}')
